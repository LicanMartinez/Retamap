//   1. Pick your name (top-left). The app loads YOUR assigned pxid list.
//   2. Walk the list with ◀ / ▶ (or type a pxid to resume where your Sheet left
//      off). Toggle year 2017 / 2025 to inspect each season.
//   3. Read the current pxid shown; fill that row in your Google Sheet:
//      class_2017, class_2017_confidence, class_2025, class_2025_confidence.
//
// REFERENCE PRIORITY: high-resolution imagery in Google Earth Pro (visible yellow
// bloom, open the matching <pxid>.kml) is the PRIMARY evidence. The mosaics and the
// Sentinel-2 NDYI series here are phenological SUPPORT only — they reuse the model's
// own features, so don't let them be the sole criterion (avoid circularity).
