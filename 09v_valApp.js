// 4. RENDER  (recenter=true on pxid change, false on year toggle)
// =============================================================================
function render(recenter) {
  if (!state.validator) return;
  var pxid = state.list[state.idx];
  var year = state.year;

  pxidBigLabel.setValue(pxid);
  progressLabel.setValue('punto ' + (state.idx + 1) + ' de ' + state.list.length +
                         ' · ' + pxid);
  pxidBox.setValue(pxid, false);   // reflect current pxid, do NOT fire onChange
  statusLabel.setValue('');

  // Point + 1 km neighbourhood (blind: contour only, no map label) --------------
  var feat    = ee.Feature(fc.filter(ee.Filter.eq('pxid', pxid)).first());
  var contour = feat.geometry();
  var centro  = contour.centroid(1);
  var aoi     = centro.buffer(500).bounds();
  state.aoi    = aoi;      // 1 km box: map extent / clip only

  // Four mosaic layers from 01_MergedBands_<year> ------------------------------
  var merged = ee.Image(ASSET_PREFIX + '01_MergedBands_' + year).clip(aoi);
  var proj10 = merged.select('B4').projection();   // 4326 prediction grid (the pixel the map classified)

  // The FC centroid is a UTM19S pixel center (points sampled on EPSG:32719), which
  // lands inside — but not centered in — the 4326 prediction pixel. Snap it to the
  // center of that 4326 pixel so the dot, the red box, and the validated chart all
  // resolve to the same prediction pixel.
  var pc = ee.Image.pixelLonLat().reproject(proj10)
    .reduceRegion({reducer: ee.Reducer.first(), geometry: centro, scale: 10});
  centro = ee.Geometry.Point([pc.get('longitude'), pc.get('latitude')]);
  state.centro = centro;   // 4326 prediction pixel center: region for the validated NDYI chart

  // Target pixel highlighted as a RASTER on the 4326 prediction grid — the same
  // grid the (snapped) centro, the dot, and the validated chart resolve to, so
  // all three coincide with the pixel the map classified. Blind: derived from
  // centro + raw imagery only, never from m2017/m2025 or predictions.
  var pixHi = ee.Image(0).byte()
    .paint(ee.FeatureCollection([ee.Feature(centro)]), 1)   // pixel under centro = 1
    .selfMask()
    .reproject(proj10);                                     // snap to prediction grid

  map.layers().reset();
  map.addLayer(aoi, {color: 'ffffff'}, '1km AOI', false);
  map.addLayer(merged, visTC, year + ' TrueColor NovDec', true);
  map.addLayer(merged.select('NDYI'), NDYI_VIS, year + ' NDYI NovDec', false);
  map.addLayer(merged, visTC_feb, year + ' TrueColor Feb', false);
  map.addLayer(merged.select('NDYI_feb'), NDYI_VIS, year + ' NDYI Feb', false);
  map.addLayer(pixHi, {palette: ['FF0000']}, 'pixel ' + pxid, true, 0.4);
  map.addLayer(centro, {color: '00FFFF'}, 'centroid', true);

  // layers().reset() above dropped any clicked marker → re-add it if still set.
  clickedLayer = null;
  addClickedMarker();

  if (recenter) map.centerObject(contour, 18);

  refreshCharts();
}

// Draw (or redraw) the user-clicked comparison point as a magenta marker.
function addClickedMarker() {
  if (!state.clicked) return;
  if (clickedLayer) map.remove(clickedLayer);
  clickedLayer = map.addLayer(state.clicked, {color: 'FF00FF'}, 'punto clickeado', true);
}


// =============================================================================
// 5. CONTROL CALLBACKS
// =============================================================================
function setValidator(name) {
  state.validator = name;
  state.list = ASSIGN[name] || [];
  state.idx = 0;
  var url = SHEET_URLS[name];
  if (url) { sheetLink.setUrl(url); sheetLink.setValue('▶ Abrí tu planilla (' + name + ')'); }
  else     { sheetLink.setUrl('');  sheetLink.setValue('(configurá SHEET_URLS para ' + name + ')'); }
  render(true);
}

function setYear(y) {
  state.year = parseInt(y, 10);
  render(false);   // keep the map view fixed when comparing years
}

function setSpan(txt) {
  var n = parseInt(txt, 10);
  if (isNaN(n) || n < 1) {
    statusLabel.setValue('⚠ Años a graficar: entero ≥ 1 (default 1).');
    spanBox.setValue(String(state.span), false);
    return;
  }
  state.span = n;
  statusLabel.setValue('');
  refreshCharts();   // only the charts depend on the window; no map re-render
}

function clearClicked() {
  if (clickedLayer) { map.remove(clickedLayer); clickedLayer = null; }
  state.clicked = null;
  refreshCharts();
}

function step(d) {
  if (!state.validator) { statusLabel.setValue('Elegí tu nombre primero.'); return; }
  var n = state.list.length;
  state.idx = Math.max(0, Math.min(n - 1, state.idx + d));
  render(true);
}

function jumpToPxid(txt) {
  if (!state.validator) { statusLabel.setValue('Elegí tu nombre primero.'); return; }
  var t = (txt || '').trim();
  if (t === state.list[state.idx]) return;   // programmatic echo, ignore
  var i = state.list.indexOf(t);
  if (i < 0) { statusLabel.setValue('⚠ ' + t + ' no está en tu lista asignada.'); return; }
  state.idx = i;
  render(true);
}


